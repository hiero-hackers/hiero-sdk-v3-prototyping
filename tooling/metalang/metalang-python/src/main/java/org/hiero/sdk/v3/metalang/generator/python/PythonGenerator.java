package org.hiero.sdk.v3.metalang.generator.python;

import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Objects;
import java.util.Set;
import java.util.SortedMap;
import java.util.SortedSet;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.stream.Collectors;
import org.hiero.sdk.v3.metalang.generator.GeneratedFile;
import org.hiero.sdk.v3.metalang.model.LinkedModel;
import org.hiero.sdk.v3.metalang.model.NamespaceDefinition;
import org.hiero.sdk.v3.metalang.model.QualifiedName;
import org.hiero.sdk.v3.metalang.model.TypeDefinition;

/**
 * Generates the Python API from a {@link LinkedModel}, following {@code guidelines/api-best-practices-python.md}: one
 * distribution ({@code pyproject.toml}, {@code py.typed}), one package per namespace that re-exports its types, and one
 * private module per type. Only the declared types are generated so far; a declaration without Python form is left out
 * and reported by {@link #deferred()}.
 */
public final class PythonGenerator {

    /** Text in the first line of every generated file; it marks the files the generator may replace or delete. */
    public static final String MARKER = "Generated by metalang from the Hiero SDK V3 specs. Do not edit.";

    /** The first line of every generated Python, TOML and ignore file. */
    static final String HEADER = "# " + MARKER + "\n";

    private final PythonGeneratorConfig config;
    private final SortedMap<QualifiedName, String> deferred = new TreeMap<>();

    /** Creates a generator with the default configuration. */
    public PythonGenerator() {
        this(PythonGeneratorConfig.DEFAULT);
    }

    /**
     * Creates a generator.
     *
     * @param config the project-specific configuration
     */
    public PythonGenerator(final PythonGeneratorConfig config) {
        this.config = Objects.requireNonNull(config, "config must not be null");
    }

    /**
     * Generates all files.
     *
     * @param model the linked model
     * @return the files, sorted by path
     */
    public List<GeneratedFile> generate(final LinkedModel model) {
        Objects.requireNonNull(model, "model must not be null");
        deferred.clear();
        final PyContext context = new PyContext(model, config);
        deferred.putAll(context.gaps());
        final PyTypeGenerator types = new PyTypeGenerator(context);
        final String root = "src/" + config.packageName();
        final List<GeneratedFile> files = new ArrayList<>(project());
        files.add(new GeneratedFile(root + "/py.typed", HEADER));
        final SortedSet<String> directories = new TreeSet<>();
        for (final NamespaceDefinition namespace : model.namespaces()) {
            final String directory = root + "/" + PyNames.packagePath(namespace.name());
            final SortedMap<String, String> exported = new TreeMap<>();
            for (final TypeDefinition definition : model.types(namespace.name())) {
                if (deferred.containsKey(definition.name())) {
                    continue;
                }
                final String module = context.module(definition.name());
                final PyImports imports = new PyImports(module, Set.of(definition.name().name()));
                final String body = types.generate(definition, imports);
                // isort and ruff: two blank lines before a class, one before any other statement (a type alias)
                final String rendered = imports.render();
                final String header = body.startsWith("class ") || body.startsWith("@") ? rendered
                        : rendered.substring(0, rendered.length() - 1);
                files.add(new GeneratedFile(directory + "/" + PyNames.module(definition.name().name()) + ".py",
                        HEADER + "\n" + header + body));
                exported.put(definition.name().name(), module);
            }
            files.add(new GeneratedFile(directory + "/__init__.py", packageModule(namespace, exported)));
            // every parent directory of a namespace is a package as well
            for (String parent = directory; parent.contains("/"); parent = parent.substring(0,
                    parent.lastIndexOf('/'))) {
                directories.add(parent);
            }
        }
        final Set<String> written = files.stream().map(GeneratedFile::path).collect(Collectors.toSet());
        for (final String directory : directories) {
            if (directory.startsWith(root) && !written.contains(directory + "/__init__.py")) {
                files.add(new GeneratedFile(directory + "/__init__.py", directory.equals(root)
                        ? HEADER + PyDoc.docstring("", "The Python API of the Hiero SDK.") : HEADER));
            }
        }
        return files.stream().sorted().toList();
    }

    /**
     * Returns the declarations that are not generated, with the reason, of the last {@link #generate} call.
     *
     * @return the deferred declarations
     */
    public SortedMap<QualifiedName, String> deferred() {
        return Collections.unmodifiableSortedMap(deferred);
    }

    /** The package of a namespace: its description as docstring, and the re-exports of its types. */
    private static String packageModule(final NamespaceDefinition namespace, final SortedMap<String, String> exported) {
        final String description = namespace.sources().stream().map(NamespaceDefinition.Source::description)
                .filter(d -> d != null && !d.isBlank()).collect(Collectors.joining("\n\n"));
        final StringBuilder py = new StringBuilder(HEADER);
        py.append(PyDoc.docstring("", description.isBlank() ? "The namespace ``" + namespace.name() + "``."
                : description));
        if (exported.isEmpty()) {
            return py.toString();
        }
        py.append('\n');
        exported.forEach((name, module) -> py.append(PyImports.statement("", module, List.of(name))));
        py.append("\n__all__ = [\n");
        exported.keySet().forEach(name -> py.append("    ").append(PyTypeGenerator.quote(name)).append(",\n"));
        return py.append("]\n").toString();
    }

    /** {@code pyproject.toml} and {@code .gitignore}. */
    private List<GeneratedFile> project() {
        final String pyproject = HEADER
                + "\n[build-system]\n"
                + "requires = [\"hatchling\"]\n"
                + "build-backend = \"hatchling.build\"\n"
                + "\n[project]\n"
                + "name = \"" + config.distribution() + "\"\n"
                + "version = \"" + config.version() + "\"\n"
                + "description = \"The Python API of the Hiero SDK.\"\n"
                + "requires-python = \">=3.12\"\n"
                + "classifiers = [\"Typing :: Typed\"]\n"
                + "\n[tool.hatch.build.targets.wheel]\n"
                + "packages = [\"src/" + config.packageName() + "\"]\n"
                + "\n[tool.ruff]\n"
                + "line-length = " + PyImports.LINE_LENGTH + "\n"
                + "\n[tool.mypy]\n"
                + "strict = true\n"
                + "python_version = \"3.12\"\n"
                + "mypy_path = \"src\"\n";
        final String gitignore = HEADER
                + "__pycache__/\n"
                + "*.egg-info/\n"
                + ".mypy_cache/\n"
                + ".venv/\n"
                + "build/\n"
                + "dist/\n";
        return List.of(new GeneratedFile("pyproject.toml", pyproject), new GeneratedFile(".gitignore", gitignore));
    }
}
